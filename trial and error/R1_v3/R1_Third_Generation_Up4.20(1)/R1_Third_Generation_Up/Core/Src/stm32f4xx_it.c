/**
  * @brief This function handles USART1 global interrupt.
  */
void USART1_IRQHandler(void)
{
  /* USER CODE BEGIN USART1_IRQn 0 */
    if (__HAL_UART_GET_FLAG(&huart1,UART_FLAG_ORE))//清除ORE错误标志位
    {
        __HAL_UART_CLEAR_OREFLAG(&huart1);
    }
	
    if (__HAL_UART_GET_FLAG(&huart1, UART_FLAG_FE))//清除FE错误标志位
    {
        __HAL_UART_CLEAR_FEFLAG(&huart1);
        // 可选择性重启DMA
    }

    if(__HAL_UART_GET_FLAG(&huart1, UART_FLAG_IDLE))//判断并清除IDLE空闲标志位，处理接收的数据 
    {
        __HAL_UART_CLEAR_IDLEFLAG(&huart1); 
        HAL_UART_DMAStop (&huart1);// 先停止DMA接收
        Receive_length = sizeof(RxMsg_USART1)/sizeof(RxMsg_USART1[0]) - __HAL_DMA_GET_COUNTER(&hdma_usart1_rx);//计算串口接收数据长度

        //数据处理
        Communicate_Js_Value.usJsLeft_Y = (RxMsg_USART1[0] << 8) | RxMsg_USART1[1]; //左摇杆Y方向值
		BlockArm_Task_Change.Reach_Area3|=RxMsg_USART1[2];//下板发来是否到达三区的标志
        Communicate_KEY = RxMsg_USART1[3];
        memcpy(&p_vision_data.x2, &RxMsg_USART1[4], 4);
 	    memcpy(&p_vision_data.y2, &RxMsg_USART1[8], 4);
 	    memcpy(&p_vision_data.yaw2, &RxMsg_USART1[12], 4);
	    memcpy(&p_vision_data.yaw3, &RxMsg_USART1[16], 4);
	    memcpy(&p_vision_data.distance, &RxMsg_USART1[20], 4);

        p_vision_data.x2/=2.0838f;
        p_vision_data.y2/=2.0838f;
        p_vision_data.distance/=2.0838f;
		    
        HAL_UART_Receive_DMA(&huart1,RxMsg_USART1,sizeof(RxMsg_USART1)/sizeof(RxMsg_USART1[0]));//重新开启DMA接收
        System_Monitor.Cnt_Communicate_Receive++;
    }
  /* USER CODE END USART1_IRQn 0 */
  HAL_UART_IRQHandler(&huart1);
  /* USER CODE BEGIN USART1_IRQn 1 */

  /* USER CODE END USART1_IRQn 1 */
}

